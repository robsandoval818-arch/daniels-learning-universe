export const READING_CURRICULUM: CurriculumSkill[] = [...READING_CORE_SKILLS, ...READING_STRETCH_SKILLS]

export function getReadingSkillById(id: string): CurriculumSkill | undefined {
  return READING_CURRICULUM.find((s) => s.id === id)
}

export function getNextReadingSkill(currentId: string): CurriculumSkill | undefined {
  const current = getReadingSkillById(currentId)
  if (!current) return READING_CORE_SKILLS[0]
  return READING_CORE_SKILLS.find((s) => s.order === current.order + 1)
}
